def chain_drawing():
    stages = ['客户', '需求', '方案', '报价', '合同', '项目', '售后']
    subs = ['360°视图', 'AI 结构化', '模板库生成', 'AI 定价建议', '合同台账', '甘特跟踪', '工单回访']
    w, h = AVAIL_W, 108
    d = Drawing(w, h)
    n = len(stages)
    arrow_w, gap = 14, 4
    box_w = (w - (n - 1) * (arrow_w + 2 * gap)) / n  # ≈ 54pt
    box_h, y0 = 56, 26
    for i, (title, sub) in enumerate(zip(stages, subs)):
        x = i * (box_w + arrow_w + 2 * gap)
        d.add(Rect(x, y0, box_w, box_h, rx=6, ry=6,
                   fillColor=SECTION_BG, strokeColor=ACCENT if i == 0 else BORDER,
                   strokeWidth=1 if i else 1.4))
        d.add(String(x + box_w / 2, y0 + box_h - 24, title,
                     fontName='MSYaHei-Bold', fontSize=11,
                     fillColor=TEXT_PRIMARY, textAnchor='middle'))
        d.add(String(x + box_w / 2, y0 + 10, sub,
                     fontName='SimHei', fontSize=7.5,
                     fillColor=TEXT_MUTED, textAnchor='middle'))
        if i < n - 1:
            ax0 = x + box_w + gap
            mid_y = y0 + box_h / 2
            d.add(Line(ax0, mid_y, ax0 + arrow_w - 5, mid_y,
                       strokeColor=ICON, strokeWidth=1.2))
            tip = ax0 + arrow_w - 1
            d.add(Polygon([tip - 5, mid_y - 3.2, tip - 5, mid_y + 3.2, tip, mid_y],
                          fillColor=ICON, strokeColor=None))
    return d


