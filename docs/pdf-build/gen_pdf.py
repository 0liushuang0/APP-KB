def stat_row(items):
    """数字一览：items = [(number, label), ...]"""
    n = len(items)
    nums = [Paragraph('<b>%s</b>' % v, S['stat_num']) for v, _ in items]
    labels = [Paragraph(l, S['stat_label']) for _, l in items]
    t = Table([nums, labels], colWidths=[AVAIL_W / n] * n, hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('BOX', (0, 0), (-1, -1), 0.8, BORDER),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('TOPPADDING', (0, 0), (-1, 0), 12),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ('TOPPADDING', (0, 1), (-1, 1), 2),
        ('BOTTOMPADDING', (0, 1), (-1, 1), 12),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
    ]))
    return t


def make_table(headers, rows, ratios, align_center_cols=()):
    assert abs(sum(ratios) - 1.0) < 1e-6
    col_widths = [r * AVAIL_W for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in headers]]
    for row in rows:
        cells = []
        for ci, cell in enumerate(row):
            st = S['td_c'] if ci in align_center_cols else S['td']
            cells.append(Paragraph(cell, st))
        data.append(cells)
    t = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(('BACKGROUND', (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    return t


def table_block(title_text, headers, rows, ratios, caption, align_center_cols=()):
    tbl = make_table(headers, rows, ratios, align_center_cols)
    out = [Spacer(1, 10)]
    if title_text:
        out.append(Paragraph(title_text, S['h3']))
    if len(rows) <= 12:
        out.append(KeepTogether([tbl, Spacer(1, 4), Paragraph(caption, S['caption'])]))
    else:
        out.append(tbl)
        out.append(Spacer(1, 4))
        out.append(Paragraph(caption, S['caption']))
    out.append(Spacer(1, 8))
    return out


